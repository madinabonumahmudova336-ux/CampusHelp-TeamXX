# CampusHelp – Change Request Document

## 1. Change Request Information

**Change Request ID:** CR-01

**Project:** CampusHelp – University Student Service Request Portal

**Requested by:** University Administration (Simulated Client)

**Responsible Person:** Project Manager

**Request:** Add an automatic email acknowledgment whenever a student submits a service request.

## 2. Description of the Requested Change

The university administration wants students to receive an automatic email confirmation after submitting a service request.

The email should inform students that their request has been successfully received.

## 3. Scope Analysis

This feature was not included in the original project scope.

It introduces an additional notification function and may require further technical work.

The proposed email acknowledgment will therefore be treated as an additional project requirement.

## 4. Estimated Effort and Cost

| Item | Estimate |
|---|---:|
| Additional effort | 3 hours |
| Hourly rate | 50,000 UZS |
| Additional cost | 150,000 UZS |

Calculation: 3 × 50,000 = 150,000 UZS.

## 5. Affected Tasks and Milestones

- T07 – Student Request Interface: The submission flow may need an email confirmation step.
- T09 – Testing: An additional test case may be required for email acknowledgment.
- T11 – Final Verification: The change must be reviewed.
- M3 – Project Execution: Prototype functionality may need to be updated.
- M4 – Monitoring and Closure: The change decision and its implementation status must be documented.

## 6. Schedule and Risk Impact

The change requires approximately three additional working hours.

It may increase the workload and create delays in testing and final verification.

There is also a risk that actual email integration cannot be completed within the project timeline.

## 7. Recommendation

**Recommended Decision: DEFER**

The team recommends deferring the actual email integration to a future development phase.

The current project focuses on project management documentation, interface mockups, and prototype demonstration. Implementing a real email notification system may exceed the original scope and create additional technical work.

The proposed email confirmation can be represented in the prototype without implementing a production email service.

## 8. Final Decision

**Decision:** Defer actual implementation.

**Reason:** The feature is useful but is outside the original project scope. Deferring it protects the current schedule and allows the team to focus on the required project deliverables.

The request and its estimated impact will remain documented for future consideration.

## 9. Conclusion

The change request was evaluated based on scope, estimated effort, cost, schedule, and project risks.

The team recommends deferring actual email integration until a future development phase while documenting the proposed confirmation functionality in the prototype.
